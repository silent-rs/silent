//! 全局工具把 `migrate`、`generate`、`healthcheck` 转发给应用自己的子命令。
//!
//! 用真实的二进制在示例应用（`examples/demo`）上验证：从子目录里执行能找到应用根目录；参数原样交过去；
//! `generate` 自动带上 `codegen` feature；应用的退出码原样返回；不在应用里时报错。
//! 每次转发都要 `cargo run` 示例应用，第一次会编译，所以这个文件比别的测试慢。

use std::net::TcpListener;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

use silent_boot_cli::forward::{APP_FILE, app_root};

fn tool() -> Command {
    Command::new(env!("CARGO_BIN_EXE_silent-boot"))
}

fn example() -> Option<PathBuf> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/demo");
    path.join(APP_FILE).is_file().then_some(path)
}

/// 在示例应用的 `sub` 子目录里执行全局工具。
fn forward_in_example(sub: &str, args: &[&str]) -> Output {
    let example = example().expect("examples/demo is generated by `silent-boot new`");
    tool()
        .current_dir(example.join(sub))
        .args(args)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .output()
        .expect("run silent-boot")
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

#[test]
fn help_lists_the_forwarded_commands_and_unknown_ones_are_rejected() {
    let output = tool().arg("--help").output().expect("help");
    assert!(output.status.success());
    let help = stdout(&output);
    for word in ["new", "dev", "migrate", "generate", "healthcheck", "--bin"] {
        assert!(help.contains(word), "{word} is listed:\n{help}");
    }
    let output = tool().arg("bogus").output().expect("bogus");
    assert_eq!(
        output.status.code(),
        Some(2),
        "clap rejects unknown subcommands"
    );
}

#[test]
fn outside_an_app_the_tool_explains_what_to_do() {
    let dir = tempfile::tempdir().expect("temp dir");
    let output = tool()
        .current_dir(dir.path())
        .args(["migrate", "status"])
        .output()
        .expect("run");
    assert_eq!(output.status.code(), Some(1));
    let text = stderr(&output);
    assert!(text.contains(APP_FILE), "{text}");
    assert!(text.contains("silent-boot new"), "{text}");
    assert!(app_root(dir.path()).is_none());
}

#[test]
fn migrate_is_forwarded_from_a_nested_directory_with_its_arguments() {
    let db = tempfile::tempdir().expect("temp dir");
    let url = format!("sqlite://{}/data/app.db", db.path().display());
    let up = forward_in_example("src/api", &["migrate", "up", "--database-url", &url]);
    assert!(up.status.success(), "{}\n{}", stdout(&up), stderr(&up));
    assert!(
        stdout(&up).contains("framework: 1 applied"),
        "{}",
        stdout(&up)
    );
    // 从子目录里执行，提示里写的是找到的应用根目录。
    assert!(stderr(&up).contains("[silent-boot] 在 "), "{}", stderr(&up));
    assert!(stderr(&up).contains("cargo run -- migrate up --database-url"));

    let status = forward_in_example(
        "migration/src",
        &["migrate", "status", "--json", "--database-url", &url],
    );
    assert!(status.status.success(), "{}", stderr(&status));
    let json: serde_json::Value = serde_json::from_str(&stdout(&status)).unwrap_or_else(|e| {
        panic!(
            "status --json must be plain JSON on stdout ({e}): {}",
            stdout(&status)
        )
    });
    assert_eq!(json[1]["scope"], "app");
    assert_eq!(json[1]["applied"].as_array().map(Vec::len), Some(1));

    let lint = forward_in_example(".", &["migrate", "lint"]);
    assert!(lint.status.success(), "{}", stdout(&lint));
    assert!(stdout(&lint).contains("没有问题"), "{}", stdout(&lint));
}

#[test]
fn generate_is_forwarded_with_the_codegen_feature_and_exit_codes_are_kept() {
    let db = tempfile::tempdir().expect("temp dir");
    let url = format!("sqlite://{}/data/app.db", db.path().display());
    let up = forward_in_example(".", &["migrate", "up", "--database-url", &url]);
    assert!(up.status.success(), "{}", stderr(&up));

    // 应用要在带 codegen feature 的情况下编译得过，实体模板和生成器的输出一致。
    let entity = forward_in_example(
        ".",
        &["generate", "entity", "--dry-run", "--database-url", &url],
    );
    assert!(
        entity.status.success(),
        "{}\n{}",
        stdout(&entity),
        stderr(&entity)
    );
    assert!(stdout(&entity).contains("3 files"), "{}", stdout(&entity));
    assert!(
        !stdout(&entity).contains("would change"),
        "{}",
        stdout(&entity)
    );
    assert!(stderr(&entity).contains("-- generate entity --dry-run"));

    // 应用的退出码原样返回：没人监听的端口上 healthcheck 以 1 退出。
    let closed = TcpListener::bind("127.0.0.1:0").expect("bind");
    let port = closed.local_addr().expect("addr").port();
    drop(closed);
    let probe = forward_in_example(
        ".",
        &[
            "healthcheck",
            "--url",
            &format!("http://127.0.0.1:{port}/healthz"),
            "--timeout",
            "1s",
        ],
    );
    assert_eq!(probe.status.code(), Some(1), "{}", stdout(&probe));
    assert!(stderr(&probe).contains("连不上"), "{}", stderr(&probe));
}
